const {test,expect}=require('@playwright/test');
test('new model signs up, saves private profile, publishes, and returns to saved profile',async({page})=>{
 const email='model-signup@example.test';
 await page.goto('/?visitors=signup');
 await page.locator('#customer-signup-email').fill(email);
 await page.locator('#customer-rules-consent').check();
 await page.getByRole('button',{name:'Email me a sign-in code',exact:true}).click();
 await expect(page.getByLabel('Six-digit email code',{exact:true})).toBeVisible();
 const codeResponse=await page.request.get('/__test/customer-code?email='+encodeURIComponent(email));expect(codeResponse.ok()).toBeTruthy();
 await page.getByLabel('Six-digit email code',{exact:true}).fill((await codeResponse.json()).code);
 await page.getByRole('button',{name:'Verify and sign in',exact:true}).click();
 await expect(page.locator('#customer-signed-in')).toBeVisible();
 await page.goto('/creative-house.html');
 await page.locator('[data-creative-workflow="profile"]').click();
 const form=page.locator('#profile-form');
 await form.locator('[name="display_name"]').fill('Signup Test Model');
 await form.locator('[name="role"]').selectOption('model');
 await form.locator('[name="location"]').fill('Columbus, Ohio');
 await form.locator('[name="bio"]').fill('Disposable test model profile for independent fashion collaboration.');
 await form.locator('[name="published"]').uncheck();
 await form.locator('button[type="submit"]').click();
 await expect(page.locator('#profile-status')).toContainText('Profile saved');
 let response=await page.request.get('/api/creative-house/my-profile');expect(response.ok()).toBeTruthy();let profile=(await response.json()).profile;
 expect(profile.role).toBe('model');expect(Boolean(profile.published)).toBe(false);
 const slug=profile.slug;
 response=await page.request.get('/api/creative-house/profiles/'+slug,{headers:{Authorization:'Bearer e2e-designer-token'}});expect(response.status()).toBe(404);
 await expect(page.locator('#portfolio-status')).toContainText('Free Portfolio');
 await form.locator('[name="published"]').check();await form.locator('button[type="submit"]').click();
 await expect(page.locator('#profile-status a')).toHaveAttribute('href','/creative-house.html?profile='+slug+'#creative-directory');
 response=await page.request.get('/api/creative-house/profiles/'+slug,{headers:{Authorization:'Bearer e2e-designer-token'}});expect(response.ok()).toBeTruthy();
 expect((await response.json()).profile.display_name).toBe('Signup Test Model');
 await page.reload();await page.locator('[data-creative-workflow="profile"]').click();
 await expect(form.locator('[name="display_name"]')).toHaveValue('Signup Test Model');
 await expect(form.locator('[name="published"]')).toBeChecked();
});
