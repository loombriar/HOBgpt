const {test,expect}=require('@playwright/test');
for(const width of [390,1280]){
 test(`Visitors Suite groups purchases, favorites, measurements and settings at ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:850});
  const email=`visitor-layout-${width}-${Date.now()}@example.test`;
  const origin='http://127.0.0.1:4173';
  const challenge=await page.request.post('/api/customer/signin-code',{headers:{Origin:origin},data:{email,acceptedRules:true}});
  expect(challenge.status()).toBe(202);
  const {requestId}=await challenge.json();
  const {code}=await (await page.request.get('/__test/customer-code?email='+encodeURIComponent(email))).json();
  expect((await page.request.post('/api/customer/verify-code',{headers:{Origin:origin},data:{requestId,code}})).ok()).toBeTruthy();
  const purchases={orders:[{id:'order-one12345',status:'paid',items:[{title:'Linen dress',quantity:1,designerName:'Studio',trackingCarrier:'USPS',trackingNumber:'123456789',trackingStatus:'in_transit'}]}]};
  await page.route('**/api/my/purchases',route=>route.fulfill({json:purchases}));
  await page.goto('/?visitors=signup');
  await expect(page.locator('#visitor-orders-list')).toContainText('Linen dress');
  await expect(page.locator('#visitor-orders-list')).toContainText('Shipped · In transit');
  await expect(page.locator('#visitor-orders-list a')).toHaveAttribute('href','https://tools.usps.com/go/TrackConfirmAction?tLabels=123456789');
  expect(await page.locator('#visitor-orders').evaluate(el=>Boolean(el.compareDocumentPosition(document.querySelector('#visitor-saved'))&Node.DOCUMENT_POSITION_FOLLOWING))).toBe(true);
  await expect(page.locator('#visitor-account-settings')).not.toHaveAttribute('open');
  await expect(page.locator('#measurement-profile-form')).toBeHidden();
  await page.getByRole('button',{name:'Save my measurements',exact:true}).click();
  await expect(page.locator('#measurement-profile-name')).toBeFocused();
  await page.getByRole('button',{name:'Account settings',exact:true}).click();
  await expect(page.locator('#customer-delete-account')).toBeVisible();
  await expect(page.locator('#customer-start-shopping')).toBeInViewport();
  expect(await page.locator('#visitor-suite-modal').evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true);
  await page.route('**/api/my/purchases',route=>route.fulfill({status:503,json:{error:'Unavailable'}}));
  await page.locator('#visitor-orders-refresh').click();
  await expect(page.locator('#visitor-orders-status')).toContainText('Purchase history could not load');
  await expect(page.locator('.visitor-order-card')).toHaveCount(0);
  await page.route('**/api/my/purchases',route=>route.fulfill({json:purchases}));
  await page.locator('#visitor-orders-refresh').click();
  await expect(page.locator('.visitor-order-card')).toHaveCount(1);
  await page.locator('#customer-signout').click();
  await expect(page.locator('#visitor-orders-status')).toHaveText('Sign in to see your purchases.');
  await expect(page.locator('.visitor-order-card')).toHaveCount(0);
  await page.getByRole('button',{name:'Back to shop',exact:true}).click();
  await expect(page.locator('#visitor-suite-modal')).not.toBeVisible();
  await expect(page.locator('#shop')).toBeFocused();
 });
}
